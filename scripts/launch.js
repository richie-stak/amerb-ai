// Cross-platform launcher used by start.bat (Windows) and start.sh (Linux/macOS).
//
// The project folder is meant to be copied to any machine and started there, so before starting
// the server this checks — and where it safely can, fixes — everything that is tied to one
// machine or one operating system rather than to the project itself:
//   - .env           created from .env.example with a fresh random session secret
//   - node_modules   (re)installed if missing, or if it was installed on a different OS/CPU
//   - Ollama         started if installed but not running; the default model pulled if missing
//   - image service  started only if its Python environment was set up on *this* OS
//   - HTTPS cert     regenerated by the server itself when the hostname changed (server/certs.js)
//
// Usage: node scripts/launch.js [--no-browser]
const { spawn, spawnSync } = require('node:child_process');
const crypto = require('node:crypto');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const IS_WINDOWS = process.platform === 'win32';
const PLATFORM_TAG = `${process.platform}-${process.arch}`;
const PLATFORM_MARKER = path.join(ROOT, 'node_modules', '.amerb-platform');
const children = [];

function log(message = '') {
  console.log(message);
}

function fail(message) {
  console.error(`\n[!] ${message}\n`);
  process.exit(1);
}

function run(command, args, options = {}) {
  // npm/ollama are .cmd shims on Windows, which only run through a shell.
  const result = spawnSync(command, args, { cwd: ROOT, stdio: 'inherit', shell: IS_WINDOWS, ...options });
  return result.status === 0;
}

function commandExists(command) {
  const probe = IS_WINDOWS ? spawnSync('where', [command], { stdio: 'ignore' }) : spawnSync('sh', ['-c', `command -v ${command}`], { stdio: 'ignore' });
  return probe.status === 0;
}

function checkNode() {
  const [major, minor] = process.versions.node.split('.').map(Number);
  if (major < 22 || (major === 22 && minor < 5)) {
    fail(`Node.js 22.5 or newer is required (this machine has ${process.versions.node}). Install it from https://nodejs.org`);
  }
}

// The session secret signs every login cookie; with the placeholder from .env.example anyone who
// has read this project's source could forge one. Replace a missing or placeholder secret with a
// random one (this signs everyone out once, which is harmless — sessions reset on restart anyway).
const PLACEHOLDER_SECRETS = ['', 'change-this-to-a-random-string', 'dev-only-secret-change-me'];

function ensureEnvFile() {
  const envPath = path.join(ROOT, '.env');
  if (!fs.existsSync(envPath)) {
    fs.copyFileSync(path.join(ROOT, '.env.example'), envPath);
    log('Created .env from .env.example.');
  }
  let env = fs.readFileSync(envPath, 'utf8');
  const current = (/^SESSION_SECRET=(.*)$/m.exec(env)?.[1] || '').trim();
  if (PLACEHOLDER_SECRETS.includes(current)) {
    const line = `SESSION_SECRET=${crypto.randomBytes(32).toString('hex')}`;
    env = /^SESSION_SECRET=/m.test(env) ? env.replace(/^SESSION_SECRET=.*$/m, line) : `${env.trimEnd()}\n${line}\n`;
    fs.writeFileSync(envPath, env);
    log('Set a new random SESSION_SECRET in .env (the old one was missing or the example placeholder).');
  }
  process.loadEnvFile(envPath);
}

// node_modules holds native binaries (image processing, speech recognition) built for the OS it
// was installed on — a folder copied from Windows to Linux would start but crash on first use.
function ensureDependencies() {
  const hasModules = fs.existsSync(path.join(ROOT, 'node_modules', 'express'));
  const installedFor = fs.existsSync(PLATFORM_MARKER) ? fs.readFileSync(PLATFORM_MARKER, 'utf8').trim() : null;

  if (hasModules && (installedFor === PLATFORM_TAG || installedFor === null)) {
    // No marker yet means an install from before this launcher existed, made on this machine.
    if (installedFor === null) fs.writeFileSync(PLATFORM_MARKER, PLATFORM_TAG);
    return;
  }

  if (hasModules) {
    log(`Dependencies were installed on ${installedFor}, but this machine is ${PLATFORM_TAG} — reinstalling them...`);
    fs.rmSync(path.join(ROOT, 'node_modules'), { recursive: true, force: true });
  } else {
    log('Installing dependencies (first run on this machine — needs internet, takes a few minutes)...');
  }
  if (!run('npm', ['ci', '--no-audit', '--no-fund'])) {
    fail('Installing dependencies failed. Check the internet connection and run "npm ci" here to see the full error.');
  }
  fs.writeFileSync(PLATFORM_MARKER, PLATFORM_TAG);
}

async function ollamaTags(url) {
  try {
    const res = await fetch(`${url}/api/tags`, { signal: AbortSignal.timeout(3000) });
    return res.ok ? await res.json() : null;
  } catch {
    return null;
  }
}

async function ensureOllama() {
  const url = process.env.OLLAMA_URL || 'http://127.0.0.1:11434';
  let tags = await ollamaTags(url);

  if (!tags && commandExists('ollama')) {
    log('Ollama is installed but not running — starting it...');
    const child = spawn('ollama', ['serve'], { detached: true, stdio: 'ignore', shell: IS_WINDOWS });
    child.unref();
    for (let i = 0; i < 20 && !tags; i++) {
      await new Promise((r) => setTimeout(r, 1000));
      tags = await ollamaTags(url);
    }
  }

  if (!tags) {
    log('');
    log('[!] Ollama is not running, so AMERB AI will start but cannot answer yet.');
    log('    Install it from https://ollama.com/download' + (IS_WINDOWS ? '' : '  (Linux: curl -fsSL https://ollama.com/install.sh | sh)'));
    log('    then run "ollama serve" and restart AMERB AI.');
    return;
  }

  // The chat model, plus the small embedding model that makes document search work by meaning.
  const required = [
    { name: process.env.DEFAULT_MODEL, role: 'default chat model', size: 'a few GB', fallback: "pick another model in the chat until it's pulled" },
    { name: process.env.EMBED_MODEL || 'nomic-embed-text', role: 'document search model', size: 'about 270 MB', fallback: 'document search uses keywords only until it is pulled' },
  ].filter((m) => m.name);
  const withTag = (n) => (n.includes(':') ? n : `${n}:latest`);
  for (const model of required) {
    const installed = (tags.models || []).some((m) => withTag(m.name) === withTag(model.name));
    if (installed) {
      log(`Ollama has the ${model.role} "${model.name}".`);
      continue;
    }
    if (!commandExists('ollama')) {
      log(`[!] The ${model.role} "${model.name}" isn't installed. Pull it on the Ollama machine with: ollama pull ${model.name}`);
      continue;
    }
    log(`Downloading the ${model.role} "${model.name}" (one-time, ${model.size})...`);
    if (!run('ollama', ['pull', model.name])) {
      log(`[!] Could not download "${model.name}". AMERB AI will start, but ${model.fallback}.`);
    }
  }
}

// A Python virtual environment only works on the OS that created it (Scripts\ on Windows,
// bin/ on Linux), so only start the image service if it was set up on this kind of machine.
function startImageService() {
  const imagegenDir = path.join(ROOT, 'imagegen');
  const python = IS_WINDOWS ? path.join(imagegenDir, 'venv', 'Scripts', 'python.exe') : path.join(imagegenDir, 'venv', 'bin', 'python');
  const setupScript = IS_WINDOWS ? 'imagegen\\setup.bat' : 'imagegen/setup.sh';

  if (!fs.existsSync(python)) {
    const otherOs = fs.existsSync(path.join(imagegenDir, 'venv'));
    log(
      otherOs
        ? `Image generation was set up on a different operating system — run ${setupScript} once to set it up here.`
        : `Image generation isn't set up (optional) — run ${setupScript} once to enable it.`
    );
    return;
  }
  log('Starting the image generation service...');
  const child = spawn(python, ['service.py'], { cwd: imagegenDir, stdio: ['ignore', 'pipe', 'pipe'] });
  const prefix = (stream) => (chunk) =>
    chunk
      .toString()
      .split(/\r?\n/)
      .filter(Boolean)
      .forEach((line) => stream.write(`[imagegen] ${line}\n`));
  child.stdout.on('data', prefix(process.stdout));
  child.stderr.on('data', prefix(process.stderr));
  child.on('exit', (code) => {
    if (code) log(`[imagegen] stopped (exit code ${code}) — image generation is unavailable; everything else still works.`);
  });
  children.push(child);
}

function openBrowser(url) {
  if (process.argv.includes('--no-browser')) return;
  if (IS_WINDOWS) spawn('cmd', ['/c', 'start', '""', url], { detached: true, stdio: 'ignore' }).unref();
  else if (process.platform === 'darwin') spawn('open', [url], { detached: true, stdio: 'ignore' }).unref();
  else if (process.env.DISPLAY || process.env.WAYLAND_DISPLAY) spawn('xdg-open', [url], { detached: true, stdio: 'ignore' }).unref();
}

function firewallHint(port) {
  if (IS_WINDOWS) {
    log(`  Other PCs can't connect? Allow Node.js through Windows Firewall when prompted, or ask IT to open TCP port ${port}.`);
  } else {
    log(`  Other PCs can't connect? Open the port, e.g.  sudo ufw allow ${port}/tcp  (or firewall-cmd --add-port=${port}/tcp).`);
  }
}

async function main() {
  process.chdir(ROOT);
  log('============================================');
  log(`  Starting AMERB AI  (${os.hostname()}, ${PLATFORM_TAG})`);
  log('============================================');
  checkNode();
  ensureEnvFile();
  ensureDependencies();
  await ensureOllama();
  startImageService();

  const port = process.env.PORT || 3000;
  log('');
  const server = spawn(process.execPath, [path.join('server', 'index.js')], { cwd: ROOT, stdio: 'inherit' });
  children.push(server);

  let opened = false;
  const readyCheck = setInterval(async () => {
    try {
      // The server's certificate is self-signed, so this one readiness probe — to our own server on
      // 127.0.0.1, carrying no data — skips verification for this request only, not process-wide.
      const https = require('node:https');
      await new Promise((resolve, reject) => {
        const req = https.get(`https://127.0.0.1:${port}/api/session`, { rejectUnauthorized: false }, (res) => {
          res.resume();
          resolve();
        });
        req.on('error', reject);
        req.setTimeout(2000, () => req.destroy(new Error('timeout')));
      });
      clearInterval(readyCheck);
      if (!opened) {
        opened = true;
        log('');
        log('  The browser will warn about the certificate the first time — that is expected (see README).');
        firewallHint(port);
        log('  Press Ctrl+C to stop AMERB AI.');
        log('');
        openBrowser(`https://localhost:${port}`);
      }
    } catch {
      /* not up yet */
    }
  }, 1000);

  server.on('exit', (code) => {
    clearInterval(readyCheck);
    for (const child of children) if (child !== server && child.exitCode === null) child.kill();
    process.exit(code ?? 0);
  });

  const shutdown = () => {
    for (const child of children) if (child.exitCode === null) child.kill();
  };
  process.on('SIGINT', shutdown);
  process.on('SIGTERM', shutdown);
}

main().catch((err) => fail(err.stack || err.message));
