// Cross-platform launcher used by start.bat (Windows) and start.sh (Linux/macOS), and — with
// --service — by the Windows service (scripts/service/install.js) and the systemd unit
// (deploy/amerb-ai.service).
//
// The project folder is meant to be copied to any machine and started there, so before starting
// the server this checks — and where it safely can, fixes — everything that is tied to one
// machine or one operating system rather than to the project itself:
//   - .env           created from .env.example with a fresh random session secret
//   - node_modules   (re)installed if missing, or if it was installed on a different OS/CPU
//   - Ollama         started if installed but not running; the default model pulled if missing
//   - image service  started only if its Python environment was set up on *this* OS
//   - HTTPS cert     regenerated by the server itself when the hostname changed (server/certs.js)
//
// Usage: node scripts/launch.js [--no-browser] [--service] [--help]
//
// Service mode (--service, or AMERB_SERVICE=1) is for running unattended under a supervisor:
//   - never opens a browser and never waits for a keypress
//   - copies everything it prints (and the server's / image service's output) to
//     <LOG_DIR>/service.log (LOG_DIR defaults to <project>/logs), rotated at ~10 MB, 5 old files kept
//   - keeps looking for Ollama in the background if it isn't up yet (it often starts after boot)
//   - exits NON-zero whenever the server dies unexpectedly so the supervisor restarts it, and on
//     SIGINT / SIGTERM / SIGBREAK / a "shutdown" message from the node-windows wrapper kills the whole
//     child tree first so nothing is left holding the ports.
const { spawn, spawnSync } = require('node:child_process');
const crypto = require('node:crypto');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const IS_WINDOWS = process.platform === 'win32';
const PLATFORM_TAG = `${process.platform}-${process.arch}`;
const PLATFORM_MARKER = path.join(ROOT, 'node_modules', '.amerb-platform');
const SERVICE_MODE = process.argv.includes('--service') || ['1', 'true', 'yes'].includes(String(process.env.AMERB_SERVICE || '').toLowerCase());
const children = [];
const timers = [];
let shuttingDown = false;
let serviceLog = null;

if (process.argv.includes('--help') || process.argv.includes('-h')) {
  console.log(
    [
      'Usage: node scripts/launch.js [options]',
      '',
      '  --no-browser   do not open the browser once the server is up',
      '  --service      unattended/service mode (also enabled by AMERB_SERVICE=1): no browser, no',
      '                 prompts, output copied to <LOG_DIR>/service.log (default <project>/logs),',
      '                 exits non-zero on a crash so the supervisor restarts it',
      '  --help         show this help',
      '',
      'Environment: PORT, HOST, LOG_DIR, OLLAMA_URL, AMERB_SERVICE (see .env.example / README).',
    ].join('\n')
  );
  process.exit(0);
}

// ---------------------------------------------------------------------------------------------
// Service-mode logging: a tiny self-contained size-rotating log file (service.log, service.log.1 …).
// ---------------------------------------------------------------------------------------------
const LOG_MAX_BYTES = 10 * 1024 * 1024;
const LOG_KEEP = 5;

class RotatingLog {
  constructor(dir, name, maxBytes = LOG_MAX_BYTES, keep = LOG_KEEP) {
    this.file = path.join(dir, name);
    this.maxBytes = maxBytes;
    this.keep = keep;
    fs.mkdirSync(dir, { recursive: true });
    this.fd = null;
    this.size = 0;
    this.open();
  }

  open() {
    this.fd = fs.openSync(this.file, 'a');
    try {
      this.size = fs.fstatSync(this.fd).size;
    } catch {
      this.size = 0;
    }
  }

  rotate() {
    try {
      fs.closeSync(this.fd);
    } catch {
      /* ignore */
    }
    this.fd = null;
    try {
      fs.rmSync(`${this.file}.${this.keep}`, { force: true });
      for (let i = this.keep - 1; i >= 1; i--) {
        if (fs.existsSync(`${this.file}.${i}`)) fs.renameSync(`${this.file}.${i}`, `${this.file}.${i + 1}`);
      }
      fs.renameSync(this.file, `${this.file}.1`);
    } catch {
      // Could not rename (e.g. another process has the file open) — start the file over instead of growing forever.
      try {
        fs.truncateSync(this.file, 0);
      } catch {
        /* ignore */
      }
    }
    this.open();
  }

  line(text) {
    if (this.fd === null) return;
    const data = `${new Date().toISOString()} ${text}\n`;
    try {
      if (this.size > 0 && this.size + Buffer.byteLength(data) > this.maxBytes) this.rotate();
      this.size += fs.writeSync(this.fd, data);
    } catch {
      /* never let logging take the app down */
    }
  }
}

// Reads LOG_DIR from the environment, falling back to the .env file (which is only loaded later).
function resolveLogDir() {
  let dir = process.env.LOG_DIR;
  if (!dir) {
    try {
      dir = (/^\s*LOG_DIR\s*=\s*(.*)$/m.exec(fs.readFileSync(path.join(ROOT, '.env'), 'utf8'))?.[1] || '').trim().replace(/^(["'])(.*)\1$/, '$2');
    } catch {
      /* no .env yet */
    }
  }
  return path.resolve(ROOT, dir || 'logs');
}

// Copy everything written to stdout/stderr into the log file, line by line.
function teeStream(stream) {
  const original = stream.write.bind(stream);
  let partial = '';
  stream.on('error', () => {}); // a closed/odd stdout under a service must not crash us
  stream.write = (chunk, encoding, callback) => {
    try {
      const text = typeof chunk === 'string' ? chunk : Buffer.from(chunk.buffer, chunk.byteOffset, chunk.byteLength).toString('utf8');
      partial += text;
      const lines = partial.split(/\r?\n/);
      partial = lines.pop();
      for (const line of lines) if (line) serviceLog.line(line);
    } catch {
      /* ignore */
    }
    return original(chunk, encoding, callback);
  };
  return () => {
    if (partial) serviceLog.line(partial);
    partial = '';
  };
}

function startServiceLogging() {
  const dir = resolveLogDir();
  try {
    serviceLog = new RotatingLog(dir, 'service.log');
  } catch (err) {
    console.error(`[!] Could not write ${path.join(dir, 'service.log')} (${err.message}) — continuing without a log file.`);
    return;
  }
  const flushers = [teeStream(process.stdout), teeStream(process.stderr)];
  process.on('exit', () => flushers.forEach((flush) => flush()));
  serviceLog.line(`---- AMERB AI service launcher starting (pid ${process.pid}, node ${process.versions.node}, ${PLATFORM_TAG}, log ${serviceLog.file}) ----`);
}

function log(message = '') {
  console.log(message);
}

// ---------------------------------------------------------------------------------------------
// Child-process handling
// ---------------------------------------------------------------------------------------------
function isAlive(child) {
  return child.exitCode === null && child.signalCode === null;
}

// Kill a child and everything it started. On Windows a plain child.kill() only ends that one
// process (a Python venv launcher or a node server would leave grandchildren holding the port).
function killTree(child, force = false) {
  if (!child || !child.pid || !isAlive(child)) return;
  if (IS_WINDOWS) {
    spawnSync('taskkill', ['/pid', String(child.pid), '/T', '/F'], { stdio: 'ignore' });
  } else {
    try {
      child.kill(force ? 'SIGKILL' : 'SIGTERM');
    } catch {
      /* already gone */
    }
  }
}

function track(child) {
  children.push(child);
  child.once('exit', () => {
    const i = children.indexOf(child);
    if (i !== -1) children.splice(i, 1);
  });
  return child;
}

// Stops everything we started, then exits with `exitCode`.
function shutdown(reason, exitCode = 0) {
  if (shuttingDown) return;
  shuttingDown = true;
  if (reason) log(`\n${reason}`);
  timers.forEach((t) => clearInterval(t));
  const alive = children.filter(isAlive);
  const finish = () => process.exit(exitCode);

  if (IS_WINDOWS || alive.length === 0) {
    alive.forEach((c) => killTree(c, true));
    finish();
    return;
  }
  // Linux/macOS: ask nicely (SIGTERM) and force-kill whatever is still there after 8 seconds.
  let remaining = alive.length;
  const done = () => --remaining <= 0 && finish();
  alive.forEach((c) => {
    c.once('exit', done);
    killTree(c);
  });
  setTimeout(() => {
    alive.forEach((c) => killTree(c, true));
    finish();
  }, 8000).unref();
}

function fail(message) {
  console.error(`\n[!] ${message}\n`);
  children.filter(isAlive).forEach((c) => killTree(c, true));
  process.exit(1);
}

function run(command, args, options = {}) {
  // npm/ollama are .cmd shims on Windows, which only run through a shell.
  if (SERVICE_MODE) {
    const result = spawnSync(command, args, { cwd: ROOT, encoding: 'utf8', shell: IS_WINDOWS, windowsHide: true, ...options, stdio: 'pipe' });
    for (const out of [result.stdout, result.stderr]) {
      String(out || '')
        .split(/\r?\n/)
        .filter(Boolean)
        .forEach((line) => log(`[${command}] ${line}`));
    }
    return result.status === 0;
  }
  const result = spawnSync(command, args, { cwd: ROOT, stdio: 'inherit', shell: IS_WINDOWS, ...options });
  return result.status === 0;
}

// Async twin of run() for long jobs (model downloads) so the launcher stays responsive to signals.
function runAsync(command, args) {
  return new Promise((resolve) => {
    const child = spawn(command, args, { cwd: ROOT, stdio: SERVICE_MODE ? 'ignore' : 'inherit', shell: IS_WINDOWS, windowsHide: SERVICE_MODE });
    track(child);
    child.on('error', () => resolve(false));
    child.on('exit', (code) => resolve(code === 0));
  });
}

function commandExists(command) {
  const probe = IS_WINDOWS ? spawnSync('where', [command], { stdio: 'ignore' }) : spawnSync('sh', ['-c', `command -v ${command}`], { stdio: 'ignore' });
  return probe.status === 0;
}

function checkNode() {
  const [major, minor] = process.versions.node.split('.').map(Number);
  if (major < 22 || (major === 22 && minor < 5)) {
    fail(`Node.js 22.5 or newer is required (this machine has ${process.versions.node}). Install it from https://nodejs.org`);
  }
}

// The session secret signs every login cookie; with the placeholder from .env.example anyone who
// has read this project's source could forge one. Replace a missing or placeholder secret with a
// random one (this signs everyone out once, which is harmless — sessions reset on restart anyway).
const PLACEHOLDER_SECRETS = ['', 'change-this-to-a-random-string', 'dev-only-secret-change-me'];

function ensureEnvFile() {
  const envPath = path.join(ROOT, '.env');
  if (!fs.existsSync(envPath)) {
    fs.copyFileSync(path.join(ROOT, '.env.example'), envPath);
    log('Created .env from .env.example.');
  }
  let env = fs.readFileSync(envPath, 'utf8');
  const current = (/^SESSION_SECRET=(.*)$/m.exec(env)?.[1] || '').trim();
  if (PLACEHOLDER_SECRETS.includes(current)) {
    const line = `SESSION_SECRET=${crypto.randomBytes(32).toString('hex')}`;
    env = /^SESSION_SECRET=/m.test(env) ? env.replace(/^SESSION_SECRET=.*$/m, line) : `${env.trimEnd()}\n${line}\n`;
    fs.writeFileSync(envPath, env);
    log('Set a new random SESSION_SECRET in .env (the old one was missing or the example placeholder).');
  }
  // Does not override variables that are already set, so PORT/LOG_DIR/... from the environment win.
  process.loadEnvFile(envPath);
}

// node_modules holds native binaries (image processing, speech recognition) built for the OS it
// was installed on — a folder copied from Windows to Linux would start but crash on first use.
function ensureDependencies() {
  const hasModules = fs.existsSync(path.join(ROOT, 'node_modules', 'express'));
  const installedFor = fs.existsSync(PLATFORM_MARKER) ? fs.readFileSync(PLATFORM_MARKER, 'utf8').trim() : null;

  if (hasModules && (installedFor === PLATFORM_TAG || installedFor === null)) {
    // No marker yet means an install from before this launcher existed, made on this machine.
    if (installedFor === null) fs.writeFileSync(PLATFORM_MARKER, PLATFORM_TAG);
    return;
  }

  if (hasModules) {
    log(`Dependencies were installed on ${installedFor}, but this machine is ${PLATFORM_TAG} — reinstalling them...`);
    fs.rmSync(path.join(ROOT, 'node_modules'), { recursive: true, force: true });
  } else {
    log('Installing dependencies (first run on this machine — needs internet, takes a few minutes)...');
  }
  if (!run('npm', ['ci', '--no-audit', '--no-fund'])) {
    fail('Installing dependencies failed. Check the internet connection and run "npm ci" here to see the full error.');
  }
  fs.writeFileSync(PLATFORM_MARKER, PLATFORM_TAG);
}

async function ollamaTags(url) {
  try {
    const res = await fetch(`${url}/api/tags`, { signal: AbortSignal.timeout(3000) });
    return res.ok ? await res.json() : null;
  } catch {
    return null;
  }
}

function ollamaUrl() {
  return process.env.OLLAMA_URL || 'http://127.0.0.1:11434';
}

// The chat model, plus the small embedding model that makes document search work by meaning.
async function ensureModels(tags) {
  const required = [
    { name: process.env.DEFAULT_MODEL, role: 'default chat model', size: 'a few GB', fallback: "pick another model in the chat until it's pulled" },
    { name: process.env.EMBED_MODEL || 'nomic-embed-text', role: 'document search model', size: 'about 270 MB', fallback: 'document search uses keywords only until it is pulled' },
  ].filter((m) => m.name);
  const withTag = (n) => (n.includes(':') ? n : `${n}:latest`);
  for (const model of required) {
    if (shuttingDown) return;
    const installed = (tags.models || []).some((m) => withTag(m.name) === withTag(model.name));
    if (installed) {
      log(`Ollama has the ${model.role} "${model.name}".`);
      continue;
    }
    if (!commandExists('ollama')) {
      log(`[!] The ${model.role} "${model.name}" isn't installed. Pull it on the Ollama machine with: ollama pull ${model.name}`);
      continue;
    }
    log(`Downloading the ${model.role} "${model.name}" (one-time, ${model.size})...`);
    if (!(await runAsync('ollama', ['pull', model.name]))) {
      if (!shuttingDown) log(`[!] Could not download "${model.name}". AMERB AI will start, but ${model.fallback}.`);
    } else {
      log(`Downloaded "${model.name}".`);
    }
  }
}

// Returns the Ollama tag list when Ollama is reachable (starting it if installed), else null.
async function connectOllama() {
  const url = ollamaUrl();
  let tags = await ollamaTags(url);

  if (!tags && commandExists('ollama')) {
    log('Ollama is installed but not running — starting it...');
    const child = spawn('ollama', ['serve'], { detached: true, stdio: 'ignore', shell: IS_WINDOWS, windowsHide: SERVICE_MODE });
    child.unref();
    for (let i = 0; i < 20 && !tags; i++) {
      await new Promise((r) => setTimeout(r, 1000));
      tags = await ollamaTags(url);
    }
  }
  return tags;
}

async function ensureOllama() {
  const tags = await connectOllama();

  if (!tags) {
    log('');
    log('[!] Ollama is not running, so AMERB AI will start but cannot answer yet.');
    if (SERVICE_MODE) {
      log('    Will keep checking every 30 seconds for up to 10 minutes (Ollama may still be starting after boot).');
      log('    If Ollama is installed for another Windows user, run the service as that user or run Ollama as its own service (see docs/WINDOWS-SERVICE.md).');
    } else {
      log('    Install it from https://ollama.com/download' + (IS_WINDOWS ? '' : '  (Linux: curl -fsSL https://ollama.com/install.sh | sh)'));
      log('    then run "ollama serve" and restart AMERB AI.');
    }
    return null;
  }
  if (!SERVICE_MODE) await ensureModels(tags); // service mode checks models in the background so it never delays the server
  return tags;
}

// Service mode: Ollama often starts a little after we do (boot order, slow disk, per-user start).
// Keep polling every 30 s for ~10 minutes, and say so in the log when it appears.
function watchForOllama() {
  const url = ollamaUrl();
  let attempts = 0;
  const timer = setInterval(async () => {
    attempts += 1;
    const tags = await ollamaTags(url);
    if (shuttingDown) return;
    if (tags) {
      clearInterval(timer);
      log(`Ollama is now reachable at ${url} (after ~${attempts * 30}s of waiting).`);
      ensureModels(tags).catch((err) => log(`[!] Checking Ollama models failed: ${err.message}`));
    } else if (attempts >= 20) {
      clearInterval(timer);
      log(`[!] Gave up waiting for Ollama at ${url} after 10 minutes. Start it, then restart the AMERB AI service (the chat will show errors until then).`);
    }
  }, 30000);
  timers.push(timer);
}

// A Python virtual environment only works on the OS that created it (Scripts\ on Windows,
// bin/ on Linux), so only start the image service if it was set up on this kind of machine.
function startImageService() {
  const imagegenDir = path.join(ROOT, 'imagegen');
  const python = IS_WINDOWS ? path.join(imagegenDir, 'venv', 'Scripts', 'python.exe') : path.join(imagegenDir, 'venv', 'bin', 'python');
  const setupScript = IS_WINDOWS ? 'imagegen\\setup.bat' : 'imagegen/setup.sh';

  if (!fs.existsSync(python)) {
    const otherOs = fs.existsSync(path.join(imagegenDir, 'venv'));
    log(
      otherOs
        ? `Image generation was set up on a different operating system — run ${setupScript} once to set it up here.`
        : `Image generation isn't set up (optional) — run ${setupScript} once to enable it.`
    );
    return;
  }
  log('Starting the image generation service...');
  const child = spawn(python, ['service.py'], { cwd: imagegenDir, stdio: ['ignore', 'pipe', 'pipe'], windowsHide: true });
  const prefix = (stream) => (chunk) =>
    chunk
      .toString()
      .split(/\r?\n/)
      .filter(Boolean)
      .forEach((line) => stream.write(`[imagegen] ${line}\n`));
  child.stdout.on('data', prefix(process.stdout));
  child.stderr.on('data', prefix(process.stderr));
  child.on('error', (err) => log(`[imagegen] could not start: ${err.message}`));
  child.on('exit', (code) => {
    if (code && !shuttingDown) log(`[imagegen] stopped (exit code ${code}) — image generation is unavailable; everything else still works.`);
  });
  track(child);
}

function openBrowser(url) {
  if (SERVICE_MODE || process.argv.includes('--no-browser')) return;
  if (IS_WINDOWS) spawn('cmd', ['/c', 'start', '""', url], { detached: true, stdio: 'ignore' }).unref();
  else if (process.platform === 'darwin') spawn('open', [url], { detached: true, stdio: 'ignore' }).unref();
  else if (process.env.DISPLAY || process.env.WAYLAND_DISPLAY) spawn('xdg-open', [url], { detached: true, stdio: 'ignore' }).unref();
}

function firewallHint(port) {
  if (IS_WINDOWS) {
    log(`  Other PCs can't connect? Allow Node.js through Windows Firewall when prompted, or ask IT to open TCP port ${port}.`);
  } else {
    log(`  Other PCs can't connect? Open the port, e.g.  sudo ufw allow ${port}/tcp  (or firewall-cmd --add-port=${port}/tcp).`);
  }
}

function installSignalHandlers() {
  const stop = (name) => () => shutdown(`Received ${name} — stopping AMERB AI...`, 0);
  process.on('SIGINT', stop('SIGINT'));
  process.on('SIGTERM', stop('SIGTERM'));
  process.on('SIGHUP', stop('SIGHUP'));
  if (IS_WINDOWS) process.on('SIGBREAK', stop('SIGBREAK'));

  process.on('uncaughtException', (err) => {
    console.error(`[!] Launcher crashed: ${err.stack || err.message}`);
    shutdown(null, 1);
  });
  process.on('unhandledRejection', (err) => {
    console.error(`[!] Launcher error: ${err?.stack || err}`);
    shutdown(null, 1);
  });

  // node-windows' wrapper forks this script with an IPC channel. On Windows a plain kill can't be
  // caught, so the wrapper asks us to stop with a 'shutdown' message — and if the wrapper dies, the
  // channel closes and we must not keep running as an orphan.
  if (SERVICE_MODE && process.send) {
    process.on('message', (msg) => {
      if (msg === 'shutdown' || msg?.type === 'shutdown') shutdown('Service stop requested — stopping AMERB AI...', 0);
    });
    process.on('disconnect', () => shutdown('Service wrapper went away — stopping AMERB AI...', 0));
  }
}

async function main() {
  process.chdir(ROOT);
  installSignalHandlers();
  if (SERVICE_MODE) startServiceLogging();
  log('============================================');
  log(`  Starting AMERB AI  (${os.hostname()}, ${PLATFORM_TAG}${SERVICE_MODE ? ', service mode' : ''})`);
  log('============================================');
  checkNode();
  ensureEnvFile();
  ensureDependencies();
  const ollamaUp = await ensureOllama();
  if (shuttingDown) return;
  if (SERVICE_MODE && !ollamaUp) watchForOllama();
  else if (SERVICE_MODE) ensureModels(ollamaUp).catch((err) => log(`[!] Checking Ollama models failed: ${err.message}`));
  startImageService();

  const port = process.env.PORT || 3000;
  log('');
  // In service mode the server's output is captured (and so ends up in service.log); otherwise it
  // goes straight to this console, exactly as before.
  const server = spawn(process.execPath, [path.join('server', 'index.js')], {
    cwd: ROOT,
    stdio: SERVICE_MODE ? ['ignore', 'pipe', 'pipe'] : 'inherit',
    windowsHide: true,
  });
  track(server);
  if (SERVICE_MODE) {
    server.stdout.pipe(process.stdout, { end: false });
    server.stderr.pipe(process.stderr, { end: false });
  }
  server.on('error', (err) => {
    log(`[!] Could not start the server: ${err.message}`);
    shutdown(null, 1);
  });

  let opened = false;
  const readyCheck = setInterval(async () => {
    try {
      // The server's certificate is self-signed, so this one readiness probe — to our own server on
      // 127.0.0.1, carrying no data — skips verification for this request only, not process-wide.
      const https = require('node:https');
      await new Promise((resolve, reject) => {
        const req = https.get(`https://127.0.0.1:${port}/api/session`, { rejectUnauthorized: false }, (res) => {
          res.resume();
          resolve();
        });
        req.on('error', reject);
        req.setTimeout(2000, () => req.destroy(new Error('timeout')));
      });
      clearInterval(readyCheck);
      if (!opened) {
        opened = true;
        log('');
        if (SERVICE_MODE) {
          log(`  AMERB AI is up on https://localhost:${port} (health check: https://localhost:${port}/health).`);
          require('./networking').printAccessInfo({ port: Number(port), log });
        } else {
          log('  The browser will warn about the certificate the first time — that is expected (see README).');
          require('./networking').printAccessInfo({ port: Number(port), log });
          log('  Press Ctrl+C to stop AMERB AI.');
        }
        log('');
        openBrowser(`https://localhost:${port}`);
      }
    } catch {
      /* not up yet */
    }
  }, 1000);
  timers.push(readyCheck);

  server.on('exit', (code, signal) => {
    if (shuttingDown) return; // we are stopping it on purpose; shutdown() finishes the exit
    // Never report success for an unexpected exit: a supervisor (node-windows, systemd) must see a failure and restart us.
    const exitCode = code || 1;
    shutdown(`The server stopped unexpectedly (${signal ? `signal ${signal}` : `exit code ${code}`}) — stopping the other services and exiting with code ${exitCode}.`, exitCode);
  });
}

main().catch((err) => fail(err.stack || err.message));
